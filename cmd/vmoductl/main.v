fn create_main_file(base_path string, project_name string) {
	lines := [
		"// " + project_name + " - VModu Application",
		"// Generated by vmoductl",
		"",
		"module main",
		"",
		"import vmodu.config",
		"import vmodu.event.bus",
		"import vmodu.infra.health",
		"import vmodu.infra.metrics",
		"import time",
		"",
		"fn main() {",
		"\tprintln(\"========================================\")",
		"\tprintln(\"  " + project_name + "\")",
		"\tprintln(\"  Powered by VModu Runtime\")",
		"\tprintln(\"========================================\")",
		"\tprintln(\"\")",
		"",
		"\tmut event_bus := bus.default()",
		"\tprintln(\"[OK] EventBus initialized\")",
		"",
		"\tmut health_checker := health.default_checker()",
		"\tprintln(\"[OK] Health check initialized\")",
		"",
		"\t_ = metrics.new_registry(\"" + project_name + "\")",
		"\tprintln(\"[OK] Metrics initialized\")",
		"",
		"\tprintln(\"\")",
		"\tprintln(\"Server starting on :8080\")",
		"\tprintln(\"\")",
		"",
		"\tfor { time.sleep(1 * time.second) }",
		"}",
	]
	write_file(base_path + "/cmd/" + project_name + "/main.v", lines.join("\n"))
}

