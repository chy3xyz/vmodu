// vmoductl - VModu CLI 脚手架工具
// 类似 goctl，快速生成项目结构和代码

module main

import os

const version = "0.1.0"

fn main() {
	if os.args.len < 2 {
		print_usage()
		return
	}

	cmd := os.args[1]
	remaining := if os.args.len > 2 { os.args[2..] } else { []string{} }

	match cmd {
		"new" { cmd_new(remaining) }
		"init" { cmd_init(remaining) }
		"generate", "gen", "g" { cmd_generate(remaining) }
		"help", "-h", "--help" { print_usage() }
		"version", "-v", "--version" { println("vmoductl version ${version}") }
		else {
			eprintln("Unknown command: ${cmd}")
			print_usage()
		}
	}
}

fn print_usage() {
	println("")
	println("VModu CLI Tool - Rapid Development Scaffold")
	println("")
	println("Usage:")
	println("  vmoductl new <project-name>      Create a new VModu project")
	println("  vmoductl init                    Initialize VModu in current directory")
	println("  vmoductl generate <type> <name>  Generate code (module, handler, api)")
	println("")
	println("Examples:")
	println("  vmoductl new myapp                    # Create new project")
	println("  vmoductl generate module user         # Generate user module")
	println("  vmoductl generate handler order       # Generate order handler")
	println("  vmoductl generate api product         # Generate product API")
	println("")
}

fn cmd_new(args []string) {
	if args.len < 1 {
		eprintln("Usage: vmoductl new <project-name>")
		return
	}

	project_name := args[0]
	project_path := "./${project_name}"

	if os.exists(project_path) {
		eprintln("Error: Directory ${project_path} already exists")
		return
	}

	println("Creating new VModu project: ${project_name}")
	println("")

	create_project_structure(project_path, project_name)

	println("")
	println("SUCCESS: Project ${project_name} created successfully!")
	println("")
	println("Next steps:")
	println("  cd ${project_name}")
	println("  vmoductl generate module user    # Generate your first module")
	println("  v run cmd/${project_name}/main.v # Run the application")
	println("")
}

fn cmd_init(args []string) {
	project_name := os.file_name(os.getwd())
	println("Initializing VModu project in current directory")
	println("")
	create_project_structure(".", project_name)
	println("")
	println("SUCCESS: Project initialized!")
	println("")
}

fn cmd_generate(args []string) {
	if args.len < 2 {
		eprintln("Usage: vmoductl generate <type> <name>")
		eprintln("")
		eprintln("Types:")
		eprintln("  module    Generate a new module")
		eprintln("  handler   Generate event handler")
		eprintln("  api       Generate API routes")
		eprintln("  config    Generate configuration")
		eprintln("")
		return
	}

	gen_type := args[0]
	name := args[1]

	match gen_type {
		"module" { generate_module(name) }
		"handler" { generate_handler(name) }
		"api" { generate_api(name) }
		"config" { generate_config(name) }
		else {
			eprintln("Unknown generate type: ${gen_type}")
		}
	}
}

fn create_project_structure(base_path string, project_name string) {
	dirs := [
		"cmd/${project_name}",
		"internal/config",
		"internal/domain/models",
		"internal/domain/events",
		"internal/modules",
		"internal/infra/persistence",
		"internal/infra/cache",
		"internal/pkg/utils",
		"api/http/middleware",
		"api/grpc/proto",
		"deployments/docker",
		"deployments/k8s",
		"scripts",
		"docs",
		"tests",
	]

	for dir in dirs {
		full_path := "${base_path}/${dir}"
		os.mkdir_all(full_path) or { continue }
		println("  [DIR] ${dir}")
	}

	create_main_file(base_path, project_name)
	create_config_file(base_path, project_name)
	create_vmodu_yaml(base_path, project_name)
	create_gitignore(base_path)
	create_readme(base_path, project_name)
	create_dockerfile(base_path, project_name)

	println("")
	println("  [FILE] Created configuration files")
}

fn write_file(path string, content string) {
	os.write_file(path, content) or {
		eprintln("Failed to write file ${path}: ${err}")
	}
}

fn capitalize(s string) string {
	if s.len == 0 { return s }
	return s[0].ascii_str().to_upper() + s[1..]
}

