fn generate_module(name string) {
	module_path := "internal/modules/" + name

	if !os.exists("internal/modules") {
		os.mkdir_all("internal/modules") or { return }
	}

	if os.exists(module_path) {
		eprintln("Module ${name} already exists")
		return
	}

	println("Generating module: ${name}")
	println("")
	os.mkdir_all(module_path) or { return }

	module_cap := capitalize(name)

	// api.v
	api_lines := [
		"// " + name + " module API",
		"",
		"module " + name,
		"",
		"import vmodu.event.bus",
		"",
		"pub interface ModuleInterface {",
		"\tinit(event_bus &bus.EventBus) !",
		"\tname() string",
		"\tversion() string",
		"}",
		"",
		"pub struct " + module_cap + "Module {",
		"pub mut:",
		"\tevent_bus &bus.EventBus",
		"}",
		"",
		"pub fn (m &" + module_cap + "Module) name() string {",
		"\treturn \"" + name + "\"",
		"}",
		"",
		"pub fn (m &" + module_cap + "Module) version() string {",
		"\treturn \"1.0.0\"",
		"}",
	]
	write_file(module_path + "/api.v", api_lines.join("\n"))

	// module.v
	module_lines := [
		"// " + name + " module implementation",
		"",
		"module " + name,
		"",
		"import vmodu.event.bus",
		"",
		"pub fn (mut m " + module_cap + "Module) init(event_bus &bus.EventBus) ! {",
		"\tm.event_bus = event_bus",
		"\tprintln(\"[" + name + "] Module initialized\")",
		"}",
		"",
		"pub fn new() &" + module_cap + "Module {",
		"\treturn &" + module_cap + "Module{}",
		"}",
	]
	write_file(module_path + "/module.v", module_lines.join("\n"))

	// events.v
	event_lines := [
		"// " + name + " module events",
		"",
		"module " + name,
		"",
		"import time",
		"",
		"pub struct " + module_cap + "CreatedEvent {",
		"pub:",
		"\tid        string",
		"\tname      string",
		"\tcreated_at i64",
		"}",
		"",
		"pub fn new_created_event(id string, name string) " + module_cap + "CreatedEvent {",
		"\treturn " + module_cap + "CreatedEvent{",
		"\t\tid: id",
		"\t\tname: name",
		"\t\tcreated_at: time.now().unix_milli()",
		"\t}",
		"}",
	]
	write_file(module_path + "/events.v", event_lines.join("\n"))

	// handler.v
	handler_lines := [
		"// " + name + " event handlers",
		"",
		"module " + name,
		"",
		"import vmodu.event.bus",
		"",
		"fn on_created(msg bus.Message) {",
		"\tprintln(\"[" + name + "] Processing created event\")",
		"}",
	]
	write_file(module_path + "/handler.v", handler_lines.join("\n"))

	// service.v
	service_lines := [
		"// " + name + " business logic",
		"",
		"module " + name,
		"",
		"import time",
		"",
		"pub struct Service {",
		"pub mut:",
		"\t// Add dependencies",
		"}",
		"",
		"pub fn new_service() &Service {",
		"\treturn &Service{}",
		"}",
		"",
		"pub fn (s &Service) Create(name string) !string {",
		"\tid := \"" + name + "_\" + time.now().unix_milli().str()",
		"\treturn id",
		"}",
	]
	write_file(module_path + "/service.v", service_lines.join("\n"))

	// repository.v
	repo_lines := [
		"// " + name + " data access",
		"",
		"module " + name,
		"",
		"pub interface Repository {",
		"\tfind_by_id(id string) ?" + module_cap,
		"\tsave(" + name + " " + module_cap + ") !",
		"}",
		"",
		"pub struct " + module_cap + " {",
		"pub mut:",
		"\tid   string",
		"\tname string",
		"}",
	]
	write_file(module_path + "/repository.v", repo_lines.join("\n"))

	println("  [OK] Created ${module_path}/api.v")
	println("  [OK] Created ${module_path}/module.v")
	println("  [OK] Created ${module_path}/events.v")
	println("  [OK] Created ${module_path}/handler.v")
	println("  [OK] Created ${module_path}/service.v")
	println("  [OK] Created ${module_path}/repository.v")
}

fn generate_handler(name string) {
	handler_path := "internal/handlers/" + name + "_handler.v"

	if !os.exists("internal/handlers") {
		os.mkdir_all("internal/handlers") or { return }
	}

	if os.exists(handler_path) {
		eprintln("Handler ${name} already exists")
		return
	}

	println("Generating handler: ${name}")

	module_cap := capitalize(name)
	lines := [
		"// " + name + " handler",
		"",
		"module handlers",
		"",
		"import vmodu.event.bus",
		"",
		"pub struct " + module_cap + "Handler {",
		"pub mut:",
		"\t// Add dependencies",
		"}",
		"",
		"pub fn new_" + name + "_handler() &" + module_cap + "Handler {",
		"\treturn &" + module_cap + "Handler{}",
		"}",
		"",
		"pub fn (h &" + module_cap + "Handler) Register(event_bus &bus.EventBus) ! {",
		"\tevent_bus.subscribe(\"" + name + ".created\", h.on_created)!",
		"}",
		"",
		"fn (h &" + module_cap + "Handler) on_created(msg bus.Message) {",
		"\tprintln(\"[" + name + "] Handling created event\")",
		"}",
	]
	write_file(handler_path, lines.join("\n"))
	println("  [OK] Created ${handler_path}")
}

