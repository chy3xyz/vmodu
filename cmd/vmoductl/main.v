fn create_dockerfile(base_path string, project_name string) {
	lines := [
		"# Build stage",
		"FROM thevlang/vlang:alpine as builder",
		"",
		"WORKDIR /app",
		"COPY . .",
		"",
		"RUN v cmd/" + project_name + "/main.v -o " + project_name,
		"",
		"# Runtime stage",
		"FROM alpine:latest",
		"",
		"RUN apk --no-cache add ca-certificates",
		"",
		"WORKDIR /root/",
		"",
		"COPY --from=builder /app/" + project_name + " .",
		"COPY vmodu.yaml .",
		"",
		"EXPOSE 8080 9090",
		"",
		"CMD [\"./" + project_name + "\"]",
	]
	write_file(base_path + "/deployments/docker/Dockerfile", lines.join("\n"))
}

